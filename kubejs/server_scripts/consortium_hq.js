// /consortium hq build. Returns { ok, text } or { ok: false, reason }.
function consortiumHqBuild(server, level, X, Y, Z, facing, layoutName, by) {
  if (consortiumHqQueue !== null) return { ok: false, reason: 'An HQ ' + consortiumHqBusyText() + ' runs: wait for its finish line.' }
  let root = consortiumHqRoot(server, false)
  if (root !== null && root.contains('box')) return { ok: false, reason: 'An HQ box is recorded (' + root.getString('layout') + ' at ' + root.getCompound('anchor').getInt('x') + ' ' + root.getCompound('anchor').getInt('y') + ' ' + root.getCompound('anchor').getInt('z') + ' facing ' + root.getString('facing') + '): run consortium hq clear first (or hq forget to keep the blocks).' }
  let loaded = consortiumHqLoad(layoutName)
  if (!loaded.ok) return loaded
  let compiled = consortiumHqCompile(level, loaded.raw, String(layoutName), X, Y, Z, facing)
  if (!compiled.ok) return compiled
  let c = compiled.c
  let box = c.box
  root = consortiumHqRoot(server, true)
  root.putString('dim', String(level.dimension))
  root.putString('layout', c.name)
  root.putString('facing', facing)
  root.putString('by', String(by))
  root.put('anchor', consortiumHqXyz(NBT.compoundTag(), X, Y, Z))
  let b = NBT.compoundTag()
  b.putInt('x1', box.x1); b.putInt('y1', box.y1); b.putInt('z1', box.z1); b.putInt('x2', box.x2); b.putInt('y2', box.y2); b.putInt('z2', box.z2)
  root.put('box', b)
  let marks = NBT.compoundTag()
  for (let name in c.marks) {
    let p = consortiumHqWorld(c, c.marks[name][0], c.marks[name][1], c.marks[name][2])
    marks.put(name, consortiumHqXyz(NBT.compoundTag(), p.getX(), p.getY(), p.getZ()))
  }
  root.put('marks', marks)
  let arena = NBT.compoundTag()
  arena.putInt('ringMin', c.arena.ringMin); arena.putInt('ringMax', c.arena.ringMax); arena.putInt('pit', c.arena.pit)
  root.put('arena', arena)
  let special = NBT.listTag()
  for (let i = 0; i < c.cells.length; i++) {
    let e = c.palette[c.cells[i].k]
    if (!e.last && e.api === '') continue
    let p = consortiumHqWorld(c, c.cells[i].lx, c.cells[i].ly, c.cells[i].lz)
    special.add(NBT.intTag(consortiumHqPack(box, p.getX(), p.getY(), p.getZ())))
    if (e.api === 'waystone') special.add(NBT.intTag(consortiumHqPack(box, p.getX(), p.getY() + 1, p.getZ())))
  }
  root.put('special', special)
  // The traps root: world coordinates for consortium_traps.js; the mode survives a rebuild (off, on or events).
  let pd = server.persistentData
  let oldMode = pd.contains(CONSORTIUM_HQ_TRAPS_ROOT) ? String(pd.getCompound(CONSORTIUM_HQ_TRAPS_ROOT).getString('mode')) : ''
  let trapsRoot = NBT.compoundTag()
  trapsRoot.putString('dim', String(level.dimension))
  trapsRoot.putString('layout', c.name)
  trapsRoot.putString('mode', oldMode || 'events')
  let am = consortiumHqWorld(c, c.marks.arena[0], c.marks.arena[1], c.marks.arena[2])
  trapsRoot.put('arena', consortiumHqXyz(NBT.compoundTag(), am.getX(), am.getY(), am.getZ()))
  let trapList = NBT.listTag()
  for (let i = 0; i < c.traps.length; i++) {
    let t = NBT.compoundTag()
    t.putString('kind', c.traps[i].kind)
    for (let part of ['cells', 'trigger']) {
      let flat = NBT.listTag()
      for (let j = 0; j < c.traps[i][part].length; j++) {
        let w = consortiumHqWorld(c, c.traps[i][part][j][0], c.traps[i][part][j][1], c.traps[i][part][j][2])
        flat.add(NBT.intTag(w.getX())); flat.add(NBT.intTag(w.getY())); flat.add(NBT.intTag(w.getZ()))
      }
      t.put(part, flat)
    }
    trapList.add(t)
  }
  trapsRoot.put('traps', trapList)
  pd.put(CONSORTIUM_HQ_TRAPS_ROOT, trapsRoot)
  root.putBoolean('forceloaded', true)
  root.putBoolean('written', false)
  root.putBoolean('built', false)
  root.remove('record')
  let chunks = consortiumHqForce(level, box, true)
  let width = box.x2 - box.x1 + 1
  let depth = box.z2 - box.z1 + 1
  let height = box.y2 - box.y1 + 1
  consortiumHqQueue = {
    kind: 'build', server: server, level: level, c: c, box: box, by: String(by), startedAt: Date.now(), startTick: server.tickCount,
    phase: 'snapshot', i: 0, todo: width * depth * height, done: 0, placements: 0, outside: 0, worst: 0, phaseWorst: {}, ticks: 0, snapshotTicks: 0,
    budget: CONSORTIUM_HQ_PER_TICK, scanBudget: CONSORTIUM_HQ_SCAN_PER_TICK, quiet: 0,
    width: width, depth: depth, height: height,
    rec: { palette: [], index: {}, runs: [], bes: [], runStart: -1, runLen: 0, runIdx: -1, runState: null },
    columns: null, audit: [],
  }
  consortiumHqLog(by + ' hq build ' + X + ' ' + Y + ' ' + Z + ' ' + facing + ' ' + c.name + ': box ' + box.x1 + ' ' + box.y1 + ' ' + box.z1 + ' to ' + box.x2 + ' ' + box.y2 + ' ' + box.z2 + ' (' + chunks + ' chunks force-loaded), ' + c.cells.length + ' layout cells, snapshot of ' + consortiumHqQueue.todo + ' positions first')
  return { ok: true, text: 'HQ build started: box ' + box.x1 + ' ' + box.y1 + ' ' + box.z1 + ' to ' + box.x2 + ' ' + box.y2 + ' ' + box.z2 + ' (' + width + ' x ' + height + ' x ' + depth + ', ' + chunks + ' chunks), ' + c.cells.length + ' layout cells plus the ground; the snapshot of ' + consortiumHqQueue.todo + ' positions runs first, the finish line follows.' }
}

// The snapshot pass: run-length encodes the pre-build state of every position of the box.
function consortiumHqSnapshotStep(q) {
  let level = q.level
  let box = q.box
  let rec = q.rec
  let ra = level.registryAccess()
  let end = Math.min(q.todo, q.i + q.scanBudget)
  for (; q.i < end; q.i++) {
    let dx = q.i % q.width
    let dz = Math.floor(q.i / q.width) % q.depth
    let dy = Math.floor(q.i / (q.width * q.depth))
    let pos = BlockPos.containing(box.x1 + dx, box.y1 + dy, box.z1 + dz)
    let state = level.getBlockState(pos)
    let packed = dx | (dy << 8) | (dz << 16)
    if (rec.runState !== null && dx !== 0 && state === rec.runState) {
      rec.runLen++
    } else {
      if (rec.runState !== null) { rec.runs.push(rec.runStart); rec.runs.push(rec.runLen | (rec.runIdx << 8)) }
      let str = String(CONSORTIUM_HQ_PARSER.serialize(state))
      let idx = rec.index[str]
      if (idx === undefined) { idx = rec.palette.length; rec.palette.push(str); rec.index[str] = idx }
      rec.runStart = packed; rec.runLen = 1; rec.runIdx = idx; rec.runState = state
    }
    if (state.hasBlockEntity()) {
      let be = level.getBlockEntity(pos)
      if (be !== null) rec.bes.push({ p: packed, t: be.saveWithoutMetadata(ra) })
    }
  }
  q.done = q.i
  if (q.i < q.todo) return false
  if (rec.runState !== null) { rec.runs.push(rec.runStart); rec.runs.push(rec.runLen | (rec.runIdx << 8)) }
  // Persist the record and save before the first world write.
  let tag = NBT.compoundTag()
  let palette = NBT.listTag()
  for (let i = 0; i < rec.palette.length; i++) palette.add(NBT.stringTag(rec.palette[i]))
  tag.put('palette', palette)
  let runs = NBT.listTag()
  for (let i = 0; i < rec.runs.length; i++) runs.add(NBT.intTag(rec.runs[i]))
  tag.put('runs', runs)
  let bes = NBT.listTag()
  for (let i = 0; i < rec.bes.length; i++) {
    let e = NBT.compoundTag()
    e.putInt('p', rec.bes[i].p)
    e.put('t', rec.bes[i].t)
    bes.add(e)
  }
  tag.put('bes', bes)
  let root = consortiumHqRoot(q.server, true)
  root.put('record', tag)
  root.putBoolean('written', true)
  q.server.runCommandSilent('save-all')
  consortiumHqLog('snapshot done: ' + q.todo + ' positions, ' + (rec.runs.length / 2) + ' runs, ' + rec.palette.length + ' states, ' + rec.bes.length + ' block entities, ' + q.snapshotTicks + ' ticks; the world is saved, the ground pass starts')
  q.rec = null
  return true
}

// Columns of the box in world coordinates with their local cell (null in the apron).
function consortiumHqColumns(q) {
  let out = []
  for (let z = q.box.z1; z <= q.box.z2; z++) {
    for (let x = q.box.x1; x <= q.box.x2; x++) out.push({ x: x, z: z, local: consortiumHqLocalOf(q.c, x, z) })
  }
  return out
}

// Every bulk write of a build (and of the wipe fallback) goes through here. A position outside the snapshot
// box could never be restored by hq clear, so it is skipped, warned once on the console and counted for the
// finish line (BADGES_AND_HQ 2.4). The compile refusals make this unreachable for a layout that passed: it
// is the safety net for the next layout bug.
function consortiumHqPlace(q, pos, state, flags) {
  let box = q.box
  let x = pos.getX(), y = pos.getY(), z = pos.getZ()
  if (x < box.x1 || x > box.x2 || y < box.y1 || y > box.y2 || z < box.z1 || z > box.z2) {
    q.outside++
    if (q.outside === 1) console.warn('[Consortium] HQ ' + q.kind + ': a write at ' + x + ' ' + y + ' ' + z + ' falls outside the box ' + box.x1 + ' ' + box.y1 + ' ' + box.z1 + ' to ' + box.x2 + ' ' + box.y2 + ' ' + box.z2 + ' and is skipped (a layout bug: the snapshot could not restore it)')
    return
  }
  let old = q.level.getBlockState(pos)
  if (old.hasBlockEntity() && old !== state) {
    // what /fill and /setblock do: a chest or barrel inside the box must not spill its items as entities
    let be = q.level.getBlockEntity(pos)
    if (be !== null) CONSORTIUM_HQ_CLEARABLE.tryClear(be)
  }
  q.level.setBlock(pos, state, flags)
  q.placements++
}

// ', 3 write(s) outside the box skipped' for the finish lines, or ''.
function consortiumHqOutsideText(q) {
  return q.outside > 0 ? ', ' + q.outside + ' write(s) outside the box skipped (see the console)' : ''
}

// The ground pass: the fill layers under every column and the ground where the layer 0 map is empty.
function consortiumHqGroundStep(q) {
  let level = q.level
  let c = q.c
  if (q.columns === null) { q.columns = consortiumHqColumns(q); q.todo = q.columns.length; q.i = 0 }
  let end = Math.min(q.todo, q.i + Math.floor(q.scanBudget / 24)) // three reads and up to three writes per column into terrain or water: the light engine makes this the slowest write (50 ms per 333 columns measured)
  for (; q.i < end; q.i++) {
    let col = q.columns[q.i]
    for (let f = 1; f <= c.foundation; f++) {
      let pos = BlockPos.containing(col.x, c.Y - f, col.z)
      let st = level.getBlockState(pos)
      if (st === c.fill) continue
      // the two layers under the floor are always the fill; deeper layers only replace air, fluids and soft blocks
      if (f > CONSORTIUM_HQ_FOUNDATION && !st.isAir() && st.isSolid() && st.getFluidState().isEmpty()) continue
      consortiumHqPlace(q, pos, c.fill, CONSORTIUM_HQ_FLAG_BULK)
    }
    let empty = col.local === null
    if (!empty) {
      let row = c.layer0[col.local.lz]
      let w = c.cellWidth
      let ch = (col.local.lx + 1) * w <= row.length ? row.substring(col.local.lx * w, (col.local.lx + 1) * w) : '.'
      empty = ch === '.' || ch === ' ' || ch === '..' || ch === '  '
    }
    if (empty) {
      let pos = BlockPos.containing(col.x, c.Y, col.z)
      if (level.getBlockState(pos) !== c.ground) consortiumHqPlace(q, pos, c.ground, CONSORTIUM_HQ_FLAG_BULK)
    }
  }
  q.done = q.i
  return q.i >= q.todo
}

// The clear pass: layers 1..clear_top of every column to air where not air.
function consortiumHqClearStep(q) {
  let level = q.level
  let c = q.c
  if (q.columns === null) { q.columns = consortiumHqColumns(q); q.i = 0 }
  let height = c.clearTop
  if (q.todo !== q.columns.length * height) { q.todo = q.columns.length * height; q.i = 0 }
  let end = Math.min(q.todo, q.i + q.scanBudget)
  for (; q.i < end; q.i++) {
    let col = q.columns[q.i % q.columns.length]
    let layer = 1 + Math.floor(q.i / q.columns.length)
    let pos = BlockPos.containing(col.x, c.Y + layer, col.z)
    if (!level.getBlockState(pos).isAir()) consortiumHqPlace(q, pos, c.air, CONSORTIUM_HQ_FLAG_BULK)
  }
  q.done = q.i
  return q.i >= q.todo
}

// The layer pass: every non-empty cell bottom to top (last and api entries wait for the finish pass).
function consortiumHqLayersStep(q) {
  let level = q.level
  let c = q.c
  let ra = level.registryAccess()
  if (q.todo !== c.cells.length) { q.todo = c.cells.length; q.i = 0 }
  let end = Math.min(q.todo, q.i + q.budget)
  for (; q.i < end; q.i++) {
    let cell = c.cells[q.i]
    let e = c.palette[cell.k]
    if (e.last || e.api !== '') continue
    let pos = consortiumHqWorld(c, cell.lx, cell.ly, cell.lz)
    consortiumHqPlace(q, pos, e.state, CONSORTIUM_HQ_FLAG_BULK)
    if (e.nbt !== null) {
      let be = level.getBlockEntity(pos)
      if (be !== null) be.loadWithComponents(e.nbt, ra)
    }
  }
  q.done = q.i
  return q.i >= q.todo
}

// The finish pass, one sub-step per tick: connect, last, api, entities, audit, release.
function consortiumHqFinishStep(q) {
  let level = q.level
  let c = q.c
  let server = q.server
  let ra = level.registryAccess()
  if (q.sub === undefined) { q.sub = 'connect'; q.i = 0; q.todo = c.cells.length; q.fixed = 0 }
  if (q.sub === 'connect') {
    let end = Math.min(q.todo, q.i + q.scanBudget)
    for (; q.i < end; q.i++) {
      let cell = c.cells[q.i]
      let e = c.palette[cell.k]
      if (!e.connect) continue
      let pos = consortiumHqWorld(c, cell.lx, cell.ly, cell.lz)
      let old = level.getBlockState(pos)
      let fixed = CONSORTIUM_HQ_BLOCK.updateFromNeighbourShapes(old, level, pos)
      if (fixed !== old) { level.setBlock(pos, fixed, CONSORTIUM_HQ_FLAG_CLIENTS); q.fixed++ }
    }
    q.done = q.i
    if (q.i < q.todo) return false
    q.sub = 'last'; q.i = 0
    return false
  }
  if (q.sub === 'last') {
    for (let i = 0; i < c.cells.length; i++) {
      let cell = c.cells[i]
      let e = c.palette[cell.k]
      if (!e.last) continue
      let pos = consortiumHqWorld(c, cell.lx, cell.ly, cell.lz)
      consortiumHqPlace(q, pos, e.state, CONSORTIUM_HQ_FLAG_CLIENTS)
      if (e.nbt !== null) {
        let be = level.getBlockEntity(pos)
        if (be !== null) be.loadWithComponents(e.nbt, ra)
      }
    }
    q.sub = 'api'
    return false
  }
  if (q.sub === 'api') {
    for (let i = 0; i < c.cells.length; i++) {
      let cell = c.cells[i]
      let e = c.palette[cell.k]
      if (e.api !== 'waystone') continue
      let pos = consortiumHqWorld(c, cell.lx, cell.ly, cell.lz)
      try {
        let opt = CONSORTIUM_HQ_WS_API.placeWaystone(level, pos, CONSORTIUM_HQ_WS_STYLES[e.style])
        if (opt.isPresent()) {
          let ws = opt.get()
          ws.setName(CONSORTIUM_HQ_COMPONENT.literal(e.name))
          ws.setVisibility(CONSORTIUM_HQ_WS_VIS[e.visibility])
          CONSORTIUM_HQ_WS_MGR.get(server).updateWaystone(ws)
          CONSORTIUM_HQ_WS_SYNC.sendWaystoneUpdateToAll(server, ws)
          q.placements += 2
          consortiumHqLog('waystone "' + e.name + '" (' + e.visibility + ') placed at ' + consortiumHqPosText(pos))
        } else {
          q.audit.push('waystone at ' + consortiumHqPosText(pos) + ' was not placed (API answered empty)')
        }
      } catch (err) { q.audit.push('waystone at ' + consortiumHqPosText(pos) + ' failed: ' + err) }
    }
    q.sub = 'entities'
    return false
  }
  if (q.sub === 'entities') {
    let dim = String(level.dimension)
    for (let i = 0; i < c.entities.length; i++) {
      let en = c.entities[i]
      let pos = consortiumHqWorld(c, en.lx, en.ly, en.lz)
      let dir = (en.dir + c.steps) % 4 // north, east, south, west clockwise
      let facingByte = [2, 5, 3, 4][dir]
      let inner = en.nbt.trim().replace(/^\{/, '').replace(/\}$/, '').trim()
      let nbt = '{Tags:["' + CONSORTIUM_HQ_TAG + '"],Facing:' + facingByte + 'b' + (inner ? ',' + inner : '') + '}'
      server.runCommandSilent('execute in ' + dim + ' run summon ' + en.summon + ' ' + consortiumHqPosText(pos) + ' ' + nbt)
      q.placements++
    }
    q.sub = 'audit'; q.i = 0; q.todo = c.cells.length
    return false
  }
  if (q.sub === 'audit') {
    let end = Math.min(q.todo, q.i + Math.floor(q.scanBudget / 2)) // canSurvive plus a state read per cell
    for (; q.i < end; q.i++) {
      let cell = c.cells[q.i]
      let e = c.palette[cell.k]
      if (e.api !== '') continue
      let pos = consortiumHqWorld(c, cell.lx, cell.ly, cell.lz)
      let st = level.getBlockState(pos)
      if (st.getBlock() !== e.state.getBlock()) q.audit.push('key ' + cell.k + ' at ' + consortiumHqPosText(pos) + ' reads ' + String(CONSORTIUM_HQ_PARSER.serialize(st)) + ' instead of ' + String(CONSORTIUM_HQ_PARSER.serialize(e.state)))
      else if (!st.canSurvive(level, pos)) q.audit.push('key ' + cell.k + ' (' + String(CONSORTIUM_HQ_PARSER.serialize(st)) + ') at ' + consortiumHqPosText(pos) + ' cannot survive there')
    }
    q.done = q.i
    if (q.i < q.todo) return false
    q.sub = 'release'
    return false
  }
  // release
  consortiumHqForce(level, q.box, false)
  let root = consortiumHqRoot(server, true)
  root.putBoolean('forceloaded', false)
  root.putBoolean('built', true)
  server.runCommandSilent('save-all')
  let ticks = server.tickCount - q.startTick
  let audit = q.audit.length === 0 ? 'survival audit clean' : 'survival audit: ' + q.audit.length + ' offender(s)'
  consortiumHqNotify(server, q.by, 'built: ' + consortiumFmt(q.placements) + ' placements in ' + ticks + ' ticks (' + q.snapshotTicks + ' snapshot), worst tick ' + q.worst + ' ms (' + consortiumHqWorstText(q) + '), ' + q.fixed + ' shapes fixed, ' + audit + consortiumHqOutsideText(q) + '. Next: consortium hq status.', q.audit.length > 0 || q.outside > 0)
  for (let i = 0; i < Math.min(CONSORTIUM_HQ_AUDIT_MAX, q.audit.length); i++) consortiumHqLog('  audit: ' + q.audit[i])
  if (q.audit.length > CONSORTIUM_HQ_AUDIT_MAX) consortiumHqLog('  audit: ' + (q.audit.length - CONSORTIUM_HQ_AUDIT_MAX) + ' more')
  return true
}

