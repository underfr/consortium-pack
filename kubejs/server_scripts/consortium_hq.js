// /consortium hq clear. Returns { ok, text } or { ok: false, reason }.
function consortiumHqClear(server, by) {
  if (consortiumHqQueue !== null) return { ok: false, reason: 'An HQ ' + consortiumHqBusyText() + ' runs: wait for its finish line.' }
  let root = consortiumHqRoot(server, false)
  let box = consortiumHqBoxOf(root)
  if (box === null) return { ok: false, reason: 'No HQ box is recorded: nothing to clear.' }
  let level = consortiumHqLevelOf(server, root.getString('dim'))
  if (!root.getBoolean('written')) {
    // The build never left the snapshot pass: nothing was written, the box is simply dropped.
    consortiumHqForce(level, box, false)
    server.persistentData.remove(CONSORTIUM_HQ_ROOT)
    consortiumHqLog(by + ' hq clear: nothing was written, the box is dropped')
    return { ok: true, text: 'Nothing was written by that build (it never left the snapshot pass): the box is dropped.' }
  }
  let q = {
    kind: 'clear', server: server, level: level, box: box, by: String(by), startedAt: Date.now(), startTick: server.tickCount,
    phase: 'kill', i: 0, todo: 1, done: 0, placements: 0, outside: 0, worst: 0, phaseWorst: {}, ticks: 0, snapshotTicks: 0,
    budget: CONSORTIUM_HQ_PER_TICK, scanBudget: CONSORTIUM_HQ_SCAN_PER_TICK, quiet: 0, audit: [],
    palette: [], runs: null, beMap: {}, special: [], wipe: false, c: null,
  }
  try {
    if (!root.contains('record')) throw new Error('no record')
    let rec = root.getCompound('record')
    let palette = rec.getList('palette', 8) // 8 = string tags
    for (let i = 0; i < palette.size(); i++) q.palette.push(consortiumHqParseState(level, String(palette.getString(i))))
    let runs = rec.getList('runs', 3) // 3 = int tags
    q.runs = runs
    q.todo = runs.size() / 2
    let bes = rec.getList('bes', 10) // 10 = compounds
    for (let i = 0; i < bes.size(); i++) {
      let e = bes.getCompound(i)
      q.beMap[e.getInt('p')] = e.getCompound('t')
    }
    let special = root.getList('special', 3)
    for (let i = 0; i < special.size(); i++) q.special.push(special.getInt(i))
  } catch (err) {
    // A record that fails to parse: the wipe fallback (air above the floor, ground at the floor, fill below).
    q.wipe = true
    let anchor = root.getCompound('anchor')
    let loaded = consortiumHqLoad(String(root.getString('layout')))
    let compiled = loaded.ok ? consortiumHqCompile(level, loaded.raw, String(root.getString('layout')), anchor.getInt('x'), anchor.getInt('y'), anchor.getInt('z'), String(root.getString('facing'))) : { ok: false }
    if (compiled.ok) q.c = compiled.c
    else q.c = { X: anchor.getInt('x'), Y: anchor.getInt('y'), Z: anchor.getInt('z'), steps: 0, ax: 0, az: 0, sizeX: 0, sizeZ: 0, clearTop: box.y2 - anchor.getInt('y'), fill: consortiumHqParseState(level, 'minecraft:cobbled_deepslate'), ground: consortiumHqParseState(level, 'minecraft:grass_block'), layer0: [] }
    consortiumHqNotify(server, by, 'the snapshot record cannot be read (' + err + '): falling back to a wipe of the box (air above the floor, ground at the floor level, fill below)', true)
  }
  root.putBoolean('forceloaded', true)
  consortiumHqForce(level, box, true)
  consortiumHqQueue = q
  consortiumHqLog(by + ' hq clear: box ' + box.x1 + ' ' + box.y1 + ' ' + box.z1 + ' to ' + box.x2 + ' ' + box.y2 + ' ' + box.z2 + (q.wipe ? ' (wipe fallback)' : ', ' + q.todo + ' runs to restore'))
  return { ok: true, text: 'HQ clear started' + (q.wipe ? ' (wipe fallback, the record was unreadable)' : ': ' + q.todo + ' runs to restore') + '; the tagged entities go first, then the terminals and the waystone, then the bulk.' }
}

function consortiumHqRestoreAt(q, pos, packed, state) {
  let level = q.level
  if (level.getBlockState(pos) !== state) { level.setBlock(pos, state, CONSORTIUM_HQ_FLAG_CLIENTS); q.placements++ }
  let nbt = q.beMap[packed]
  if (nbt !== undefined) {
    let be = level.getBlockEntity(pos)
    if (be !== null) be.loadWithComponents(nbt, level.registryAccess())
  }
}

// The recorded state of one packed position (a linear search over the runs: the preface has a few cells).
function consortiumHqRecordedState(q, packed) {
  let dx = packed & 255, dy = (packed >> 8) & 255, dz = (packed >> 16) & 255
  for (let i = 0; i < q.runs.size(); i += 2) {
    let start = q.runs.getInt(i)
    let v = q.runs.getInt(i + 1)
    let len = v & 255
    if (((start >> 8) & 255) !== dy || ((start >> 16) & 255) !== dz) continue
    let sx = start & 255
    if (dx >= sx && dx < sx + len) return q.palette[v >> 8]
  }
  return null
}

function consortiumHqClearStepRun(q) {
  let server = q.server
  let level = q.level
  let box = q.box
  if (q.phase === 'kill') {
    server.runCommandSilent('execute in ' + String(level.dimension) + ' run kill @e[tag=' + CONSORTIUM_HQ_TAG + ',x=' + box.x1 + ',y=' + box.y1 + ',z=' + box.z1 + ',dx=' + (box.x2 - box.x1) + ',dy=' + (box.y2 - box.y1) + ',dz=' + (box.z2 - box.z1) + ']')
    q.phase = q.wipe ? 'wipe' : 'preface'
    q.i = 0
    return false
  }
  if (q.phase === 'preface') {
    // The terminals (their removal releases the panels in one scan) and the waystone halves, in one tick.
    for (let i = 0; i < q.special.length; i++) {
      let state = consortiumHqRecordedState(q, q.special[i])
      if (state !== null) consortiumHqRestoreAt(q, consortiumHqUnpack(box, q.special[i]), q.special[i], state)
    }
    q.phase = 'restore'
    q.i = 0
    q.done = 0
    return false
  }
  if (q.phase === 'restore') {
    let count = 0
    while (q.i < q.todo && count < q.budget) {
      let start = q.runs.getInt(q.i * 2)
      let v = q.runs.getInt(q.i * 2 + 1)
      let len = v & 255
      let state = q.palette[v >> 8]
      for (let k = 0; k < len; k++) consortiumHqRestoreAt(q, consortiumHqUnpack(box, start + k), start + k, state)
      count += len
      q.i++
    }
    q.done = q.i
    if (q.i < q.todo) return false
    q.phase = 'release'
    return false
  }
  if (q.phase === 'wipe') {
    let c = q.c
    if (q.columns === undefined) {
      q.columns = []
      for (let z = box.z1; z <= box.z2; z++) for (let x = box.x1; x <= box.x2; x++) q.columns.push({ x: x, z: z })
      q.todo = q.columns.length
      q.i = 0
      q.air = consortiumHqParseState(level, 'minecraft:air')
    }
    let end = Math.min(q.todo, q.i + Math.floor(q.scanBudget / (c.clearTop + 3)))
    for (; q.i < end; q.i++) {
      let col = q.columns[q.i]
      for (let y = c.Y + 1; y <= box.y2; y++) {
        let pos = BlockPos.containing(col.x, y, col.z)
        if (!level.getBlockState(pos).isAir()) consortiumHqPlace(q, pos, q.air, CONSORTIUM_HQ_FLAG_CLIENTS)
      }
      consortiumHqPlace(q, BlockPos.containing(col.x, c.Y, col.z), c.ground, CONSORTIUM_HQ_FLAG_CLIENTS)
      for (let y = box.y1; y < c.Y; y++) consortiumHqPlace(q, BlockPos.containing(col.x, y, col.z), c.fill, CONSORTIUM_HQ_FLAG_CLIENTS)
    }
    q.done = q.i
    if (q.i < q.todo) return false
    q.phase = 'release'
    return false
  }
  // release: the ticket, the record, the box, the marks and the traps go; the world is saved.
  consortiumHqForce(level, box, false)
  server.persistentData.remove(CONSORTIUM_HQ_ROOT)
  server.persistentData.remove(CONSORTIUM_HQ_TRAPS_ROOT)
  server.runCommandSilent('save-all')
  let ticks = server.tickCount - q.startTick
  consortiumHqNotify(server, q.by, 'cleared: ' + consortiumFmt(q.placements) + ' blocks restored in ' + ticks + ' ticks, worst tick ' + q.worst + ' ms (' + consortiumHqWorstText(q) + ')' + (q.wipe ? ' (wipe fallback)' : '') + consortiumHqOutsideText(q) + '; the record, the box and the marks are dropped.', q.wipe || q.outside > 0)
  return true
}

// ---- the tick step and the lazy interrupted check ------------------------------------------------------------

function consortiumHqStep(server) {
  let q = consortiumHqQueue
  let start = Date.now()
  let finished = false
  try {
    if (q.kind === 'clear') {
      finished = consortiumHqClearStepRun(q)
    } else if (q.phase === 'snapshot') {
      q.snapshotTicks++
      if (consortiumHqSnapshotStep(q)) { q.phase = 'ground'; q.i = 0; q.columns = null }
    } else if (q.phase === 'ground') {
      if (consortiumHqGroundStep(q)) { q.phase = 'clear'; q.i = 0; q.todo = 0 }
    } else if (q.phase === 'clear') {
      if (consortiumHqClearStep(q)) { q.phase = 'layers'; q.i = 0; q.todo = 0 }
    } else if (q.phase === 'layers') {
      if (consortiumHqLayersStep(q)) { q.phase = 'finish'; q.i = 0 }
    } else if (q.phase === 'finish') {
      finished = consortiumHqFinishStep(q)
    }
  } catch (err) {
    console.error('[Consortium] HQ ' + q.kind + ' failed in phase ' + q.phase + ': ' + err)
    consortiumHqNotify(server, q.by, q.kind + ' aborted in phase ' + q.phase + ' (' + err + '): the force-load ticket is released; run consortium hq clear to restore the snapshot' + (q.kind === 'clear' ? ' again' : '') + '.', true)
    consortiumHqForce(q.level, q.box, false)
    let root = consortiumHqRoot(server, false)
    if (root !== null) root.putBoolean('forceloaded', false)
    consortiumHqQueue = null
    return
  }
  let ms = Date.now() - start
  q.ticks++
  if (ms > q.worst) q.worst = ms
  let phaseKey = q.kind === 'clear' ? q.phase : (q.phase === 'finish' && q.sub ? 'finish/' + q.sub : q.phase)
  if (q.phaseWorst[phaseKey] === undefined || ms > q.phaseWorst[phaseKey]) q.phaseWorst[phaseKey] = ms
  if (ms > CONSORTIUM_HQ_SLOW_MS) {
    q.budget = Math.max(CONSORTIUM_HQ_BUDGET_FLOOR, Math.floor(q.budget / 2))
    q.scanBudget = Math.max(CONSORTIUM_HQ_BUDGET_FLOOR * 10, Math.floor(q.scanBudget / 2))
    q.quiet = 0
  } else if (++q.quiet >= CONSORTIUM_HQ_QUIET_STEPS) {
    q.quiet = 0
    q.budget = Math.min(CONSORTIUM_HQ_PER_TICK, q.budget * 2)
    q.scanBudget = Math.min(CONSORTIUM_HQ_SCAN_PER_TICK, q.scanBudget * 2)
  }
  if (finished) consortiumHqQueue = null
}

// A build or clear interrupted by /reload, a crash or a stop left its force-load ticket: release it and warn.
function consortiumHqLazyCheck(server) {
  let root = consortiumHqRoot(server, false)
  if (root === null || !root.getBoolean('forceloaded')) return
  let box = consortiumHqBoxOf(root)
  if (box !== null) consortiumHqForce(consortiumHqLevelOf(server, root.getString('dim')), box, false)
  root.putBoolean('forceloaded', false)
  let text = root.getBoolean('built') ? 'clear interrupted: run hq clear again' : 'build interrupted: run hq clear, then hq build'
  consortiumHqNotify(server, '', text + ' (the force-load ticket is released).', true)
}

ServerEvents.tick((event) => {
  if (consortiumHqQueue === null) {
    if (!consortiumHqChecked) {
      consortiumHqChecked = true
      try { consortiumHqLazyCheck(event.server) } catch (err) { console.error('[Consortium] HQ interrupted-run check failed: ' + err) }
    }
    return
  }
  consortiumHqStep(event.server)
})

