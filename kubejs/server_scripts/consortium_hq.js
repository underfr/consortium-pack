// ---- JSON access (JsonIO.read gives a Java map; lists are java.util.List) ----------------------------

function consortiumHqGet(o, k) {
  if (o === null || o === undefined) return undefined
  try {
    if (typeof o.get === 'function') {
      let v = o.get(k)
      if (v !== null && v !== undefined) return v
    }
  } catch (err) { /* not a map */ }
  try { return o[k] } catch (err) { return undefined }
}

function consortiumHqKeys(o) {
  let out = []
  if (o === null || o === undefined) return out
  try {
    if (typeof o.keySet === 'function') {
      for (let k of o.keySet()) out.push(String(k))
      return out
    }
  } catch (err) { /* not a map */ }
  for (let k in o) out.push(String(k))
  return out
}

function consortiumHqList(v) {
  let out = []
  if (v === null || v === undefined) return out
  try {
    if (typeof v.size === 'function' && typeof v.get === 'function') {
      for (let i = 0; i < v.size(); i++) out.push(v.get(i))
      return out
    }
  } catch (err) { /* not a list */ }
  if (typeof v.length === 'number') for (let i = 0; i < v.length; i++) out.push(v[i])
  return out
}

function consortiumHqStr(o, k, fallback) {
  let v = consortiumHqGet(o, k)
  return v === null || v === undefined ? (fallback === undefined ? '' : fallback) : String(v)
}

function consortiumHqInt(o, k, fallback) {
  let v = consortiumHqGet(o, k)
  if (v === null || v === undefined) return fallback
  let n = parseInt(String(v), 10)
  return isNaN(n) ? fallback : n
}

function consortiumHqInts(v) {
  let raw = consortiumHqList(v)
  let out = []
  for (let i = 0; i < raw.length; i++) out.push(parseInt(String(raw[i]), 10))
  return out
}

// ---- persistent root ----------------------------------------------------------------------------------

function consortiumHqRoot(server, create) {
  let pd = server.persistentData
  if (!pd.contains(CONSORTIUM_HQ_ROOT)) {
    if (!create) return null
    pd.put(CONSORTIUM_HQ_ROOT, NBT.compoundTag())
  }
  return pd.getCompound(CONSORTIUM_HQ_ROOT)
}

function consortiumHqXyz(tag, x, y, z) {
  tag.putInt('x', x); tag.putInt('y', y); tag.putInt('z', z)
  return tag
}

function consortiumHqBoxOf(root) {
  if (root === null || !root.contains('box')) return null
  let b = root.getCompound('box')
  return { x1: b.getInt('x1'), y1: b.getInt('y1'), z1: b.getInt('z1'), x2: b.getInt('x2'), y2: b.getInt('y2'), z2: b.getInt('z2') }
}

function consortiumHqPack(box, x, y, z) {
  return (x - box.x1) | ((y - box.y1) << 8) | ((z - box.z1) << 16)
}

function consortiumHqUnpack(box, p) {
  return BlockPos.containing(box.x1 + (p & 255), box.y1 + ((p >> 8) & 255), box.z1 + ((p >> 16) & 255))
}

function consortiumHqLevelOf(server, dim) {
  let level = server.getLevel(CONSORTIUM_RL.parse(String(dim)))
  return level === null || level === undefined ? server.overworld() : level
}

// ---- states, rotation, NBT ---------------------------------------------------------------------------

function consortiumHqParseState(level, str) {
  return CONSORTIUM_HQ_PARSER.parseForBlock(level.registryAccess().lookupOrThrow(CONSORTIUM_HQ_REGISTRIES.BLOCK), String(str), false).blockState()
}

function consortiumHqRotationOf(steps) {
  return steps === 1 ? CONSORTIUM_HQ_ROTATION.CLOCKWISE_90 : steps === 2 ? CONSORTIUM_HQ_ROTATION.CLOCKWISE_180 : steps === 3 ? CONSORTIUM_HQ_ROTATION.COUNTERCLOCKWISE_90 : CONSORTIUM_HQ_ROTATION.NONE
}

// Rotates a state by `steps` clockwise quarter turns (BADGES_AND_HQ 2.4): the block's own rotate() first
// (vanilla facing, axis, sign rotation and multipart properties), then, when it returned the same state,
// the generic property walk (a mod block that does not override rotate(): horizontal `facing`, `axis`,
// the north/east/south/west and x/z booleans, the 16-step `rotation`). A `states` map in the palette
// overrides both.
function consortiumHqRotateState(state, steps) {
  if (steps === 0) return state
  let rot = consortiumHqRotationOf(steps)
  let rotated = state.rotate(rot)
  if (rotated !== state) return rotated // === unwraps both sides (Object.equals is not exposed to scripts)
  let out = state
  let props = {}
  for (let prop of state.getProperties()) {
    let name = String(prop.getName())
    props[name] = prop
    let cls = String(prop.getValueClass().getName())
    let v = state.getValue(prop)
    if (cls === 'net.minecraft.core.Direction') {
      if (v.getAxis().isHorizontal()) out = out.setValue(prop, rot.rotate(v))
    } else if (cls === 'net.minecraft.core.Direction$Axis') {
      if (steps % 2 === 1 && !v.isVertical()) out = out.setValue(prop, v === CONSORTIUM_HQ_AXIS.X ? CONSORTIUM_HQ_AXIS.Z : CONSORTIUM_HQ_AXIS.X)
    } else if (name === 'rotation' && cls === 'java.lang.Integer') {
      out = out.setValue(prop, rot.rotate(v, 16))
    }
  }
  let sides = ['north', 'east', 'south', 'west']
  if (props.north && props.east && props.south && props.west) {
    let old = {}
    for (let i = 0; i < 4; i++) old[sides[i]] = state.getValue(props[sides[i]])
    for (let i = 0; i < 4; i++) out = out.setValue(props[sides[(i + steps) % 4]], old[sides[i]])
  }
  if (steps % 2 === 1 && props.x && props.z) {
    let ox = state.getValue(props.x)
    let oz = state.getValue(props.z)
    out = out.setValue(props.x, oz).setValue(props.z, ox)
  }
  return out
}

// The verified front_text NBT of a waxed wall sign (four plain lines, a dye colour).
function consortiumHqSignNbt(lines, color) {
  let msgs = []
  for (let i = 0; i < 4; i++) {
    let text = JSON.stringify({ text: String(lines[i] === undefined || lines[i] === null ? '' : lines[i]) })
    msgs.push("'" + text.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'")
  }
  return '{front_text:{messages:[' + msgs.join(',') + '],color:"' + color + '",has_glowing_text:0b},is_waxed:1b}'
}

function consortiumHqNbt(snbt) {
  return CONSORTIUM_HQ_TAGPARSER.parseTag(String(snbt))
}

// ---- layout loading and compilation -----------------------------------------------------------------

function consortiumHqLoad(name) {
  if (!/^[a-z0-9_]{1,32}$/.test(String(name))) return { ok: false, reason: 'A layout name is [a-z0-9_]{1,32}.' }
  let path = CONSORTIUM_HQ_DATA + name + '.json'
  let raw = null
  try { raw = JsonIO.read(path) } catch (err) { return { ok: false, reason: path + ' is unreadable: ' + err } }
  if (raw === null || raw === undefined) return { ok: false, reason: path + ' is missing.' }
  return { ok: true, raw: raw, path: path }
}

// Local (lx, lz) of a world column, or null outside the rectangle (the apron).
function consortiumHqLocalOf(c, x, z) {
  let rx = x - c.X
  let rz = z - c.Z
  let dx, dz
  if (c.steps === 0) { dx = rx; dz = rz } else if (c.steps === 1) { dx = rz; dz = -rx } else if (c.steps === 2) { dx = -rx; dz = -rz } else { dx = -rz; dz = rx }
  let lx = dx + c.ax
  let lz = dz + c.az
  if (lx < 0 || lx >= c.sizeX || lz < 0 || lz >= c.sizeZ) return null
  return { lx: lx, lz: lz }
}

// World position of a local cell (BADGES_AND_HQ 2.4: (dx, dz) becomes (-dz, dx) per clockwise step).
function consortiumHqWorld(c, lx, ly, lz) {
  let dx = lx - c.ax
  let dz = lz - c.az
  let rx, rz
  if (c.steps === 0) { rx = dx; rz = dz } else if (c.steps === 1) { rx = -dz; rz = dx } else if (c.steps === 2) { rx = -dx; rz = -dz } else { rx = dz; rz = -dx }
  return BlockPos.containing(c.X + rx, c.Y + ly, c.Z + rz)
}

function consortiumHqDirIndex(name) {
  return ['north', 'east', 'south', 'west'].indexOf(String(name))
}

// Parses, validates and rotates a layout for one build: refusal string in `reason`, else the compiled object.
function consortiumHqCompile(level, raw, name, X, Y, Z, facing) {
  let steps = CONSORTIUM_HQ_FACINGS.indexOf(facing)
  if (steps < 0) return { ok: false, reason: 'Facing must be south, west, north or east.' }
  let format = consortiumHqInt(raw, 'format', 0)
  if (format !== 1 && format !== 2) return { ok: false, reason: 'Layout format must be 1 or 2.' }
  // Format 2: cell_width characters per cell (1 or 2) and up to 4096 palette keys; an all-dot or all-space cell is empty.
  let cellWidth = format === 2 && consortiumHqInt(raw, 'cell_width', 1) === 2 ? 2 : 1
  let size = consortiumHqInts(consortiumHqGet(raw, 'size'))
  if (size.length !== 2 || size[0] < 1 || size[0] > 255 || size[1] < 1 || size[1] > 255) return { ok: false, reason: 'size must be [columns 1..255, rows 1..255].' }
  let anchor = consortiumHqInts(consortiumHqGet(raw, 'anchor'))
  if (anchor.length !== 2) return { ok: false, reason: 'anchor must be [x, z].' }
  let c = {
    name: name, X: X, Y: Y, Z: Z, facing: facing, steps: steps, sizeX: size[0], sizeZ: size[1], ax: anchor[0], az: anchor[1],
    apron: Math.max(0, consortiumHqInt(raw, 'apron', 3)), clearTop: consortiumHqInt(raw, 'clear_top', 24),
    palette: {}, cells: [], entities: [], marks: {}, layer0: [], cellWidth: cellWidth, traps: [],
    foundation: Math.max(1, Math.min(16, consortiumHqInt(raw, 'foundation', CONSORTIUM_HQ_FOUNDATION))),
  }
  if (c.clearTop < 1 || c.clearTop > 255) return { ok: false, reason: 'clear_top must be 1..255.' }
  // Every write of a build must lie inside the snapshot box (layers -foundation..clear_top): a cell outside it
  // would be placed but never snapshotted, so hq clear could not restore it (the record's packed offsets cannot
  // even represent it). One message for the three refusals below.
  let boxLayers = 'the snapshot box holds layers -' + c.foundation + '..' + c.clearTop + ' (clear_top): hq clear could never restore it.'
  try {
    c.fill = consortiumHqParseState(level, consortiumHqStr(raw, 'fill', 'minecraft:cobbled_deepslate'))
    c.ground = consortiumHqParseState(level, consortiumHqStr(raw, 'ground', 'minecraft:grass_block'))
    c.air = consortiumHqParseState(level, 'minecraft:air')
  } catch (err) { return { ok: false, reason: 'fill or ground state: ' + err } }
  let arena = consortiumHqGet(raw, 'arena')
  let ring = consortiumHqInts(consortiumHqGet(arena, 'ring'))
  c.arena = { ringMin: ring.length === 2 ? ring[0] : 8, ringMax: ring.length === 2 ? ring[1] : 40, pit: consortiumHqInt(arena, 'pit', 0) }
  // Palette: one parsed and rotated state per key (170 ms for 32k blocks against 771 ms when parsed per block).
  let palette = consortiumHqGet(raw, 'palette')
  let keys = consortiumHqKeys(palette)
  let maxKeys = format === 2 ? 4096 : 92
  if (keys.length === 0 || keys.length > maxKeys) return { ok: false, reason: 'The palette holds ' + keys.length + ' keys (1..' + maxKeys + ').' }
  for (let i = 0; i < keys.length; i++) {
    let k = keys[i]
    if (k.length !== cellWidth || /^[. ]+$/.test(k)) return { ok: false, reason: 'Palette key "' + k + '" is not ' + cellWidth + ' printable character(s).' }
    let def = consortiumHqGet(palette, k)
    let entry = { key: k, connect: false, last: false, api: '', nbt: null, state: null, def: def }
    // A Java String from the map is typeof 'object' in this Rhino: a plain entry is anything that is not a map.
    let isMap = def !== null && def !== undefined && typeof def.get === 'function' && typeof def.keySet === 'function'
    if (!isMap) {
      try { entry.state = consortiumHqRotateState(consortiumHqParseState(level, String(def)), steps) } catch (err) { return { ok: false, reason: 'Palette ' + k + ': ' + err } }
    } else {
      entry.api = consortiumHqStr(def, 'api')
      if (entry.api === 'waystone') {
        entry.style = consortiumHqStr(def, 'style', 'DEFAULT')
        entry.name = consortiumHqStr(def, 'name', 'HQ')
        entry.visibility = consortiumHqStr(def, 'visibility', 'ACTIVATION')
        if (!CONSORTIUM_HQ_HAS_WAYSTONES) return { ok: false, reason: 'Palette ' + k + ' needs the Waystones mod.' }
      } else if (entry.api !== '') {
        return { ok: false, reason: 'Palette ' + k + ': unknown api ' + entry.api + '.' }
      } else {
        entry.connect = String(consortiumHqGet(def, 'connect')) === 'true'
        entry.last = String(consortiumHqGet(def, 'last')) === 'true'
        let states = consortiumHqGet(def, 'states')
        let stateStr = states !== undefined && states !== null && consortiumHqGet(states, facing) !== undefined ? consortiumHqStr(states, facing) : ''
        try {
          entry.state = stateStr ? consortiumHqParseState(level, stateStr) : consortiumHqRotateState(consortiumHqParseState(level, consortiumHqStr(def, 'state')), steps)
        } catch (err) { return { ok: false, reason: 'Palette ' + k + ': ' + err } }
        let sign = consortiumHqGet(def, 'sign')
        let nbt = consortiumHqGet(def, 'nbt')
        try {
          if (sign !== undefined && sign !== null) {
            let lines = consortiumHqList(sign)
            if (lines.length !== 4) return { ok: false, reason: 'Palette ' + k + ': sign must be four lines.' }
            entry.nbt = consortiumHqNbt(consortiumHqSignNbt(lines, consortiumHqStr(def, 'color', 'black')))
          } else if (nbt !== undefined && nbt !== null) {
            let text = String(nbt)
            if (/LootTable/i.test(text)) return { ok: false, reason: 'Palette ' + k + ': a LootTable is refused (rule 4.1).' }
            entry.nbt = consortiumHqNbt(text)
          }
        } catch (err) { return { ok: false, reason: 'Palette ' + k + ' NBT: ' + err } }
      }
    }
    c.palette[k] = entry
  }
  // Layers: rows of size.z strings of size.x characters; '.' and ' ' are empty.
  let layers = consortiumHqList(consortiumHqGet(raw, 'layers'))
  if (layers.length === 0) return { ok: false, reason: 'The layout has no layers.' }
  let byY = {}
  let order = []
  for (let i = 0; i < layers.length; i++) {
    let y = consortiumHqInt(layers[i], 'y', null)
    if (y === null) return { ok: false, reason: 'Layer ' + i + ' has no y.' }
    if (y < -c.foundation || y > c.clearTop) return { ok: false, reason: 'Layer ' + y + ' lies outside the box: ' + boxLayers }
    if (byY[y] !== undefined) return { ok: false, reason: 'Layer ' + y + ' appears twice.' }
    byY[y] = layers[i]
    order.push(y)
  }
  order.sort((a, b) => a - b)
  let rowsOf = (layer, depth) => {
    let same = consortiumHqGet(layer, 'same_as')
    if (same !== undefined && same !== null) {
      let src = byY[parseInt(String(same), 10)]
      if (src === undefined || depth > 4) return null
      return rowsOf(src, depth + 1)
    }
    return consortiumHqList(consortiumHqGet(layer, 'rows'))
  }
  for (let li = 0; li < order.length; li++) {
    let y = order[li]
    let rows = rowsOf(byY[y], 0)
    if (rows === null) return { ok: false, reason: 'Layer ' + y + ': same_as points nowhere.' }
    if (rows.length !== c.sizeZ) return { ok: false, reason: 'Layer ' + y + ' has ' + rows.length + ' rows, expected ' + c.sizeZ + '.' }
    for (let z = 0; z < rows.length; z++) {
      let row = String(rows[z])
      if (row.length !== c.sizeX * cellWidth) return { ok: false, reason: 'Layer ' + y + ' row ' + z + ' has ' + row.length + ' characters, expected ' + (c.sizeX * cellWidth) + '.' }
      if (y === 0) c.layer0.push(row)
      for (let x = 0; x < c.sizeX; x++) {
        let ch = cellWidth === 1 ? row.charAt(x) : row.substring(x * cellWidth, (x + 1) * cellWidth)
        if (ch === '.' || ch === ' ' || ch === '..' || ch === '  ') continue
        if (c.palette[ch] === undefined) return { ok: false, reason: 'Layer ' + y + ' row ' + z + ' column ' + x + ': key "' + ch + '" is not in the palette.' }
        // An api cell (the waystone) owns the cell above it too: both halves must stay inside the box.
        if (c.palette[ch].api !== '' && y + 1 > c.clearTop) return { ok: false, reason: 'Layer ' + y + ' row ' + z + ' column ' + x + ': the ' + c.palette[ch].api + ' cell "' + ch + '" needs its upper half at layer ' + (y + 1) + ', outside the box: ' + boxLayers }
        c.cells.push({ lx: x, ly: y, lz: z, k: ch })
      }
    }
  }
  if (c.layer0.length === 0) for (let z = 0; z < c.sizeZ; z++) c.layer0.push('')
  // Entities and marks.
  let ents = consortiumHqList(consortiumHqGet(raw, 'entities'))
  for (let i = 0; i < ents.length; i++) {
    let at = consortiumHqInts(consortiumHqGet(ents[i], 'at'))
    let dir = consortiumHqDirIndex(consortiumHqStr(ents[i], 'facing'))
    let summon = consortiumHqStr(ents[i], 'summon')
    if (at.length !== 3 || dir < 0 || !/^[a-z0-9_.-]+:[a-z0-9_./-]+$/.test(summon)) return { ok: false, reason: 'Entity ' + i + ' needs at [x,y,z], a horizontal facing and a summon id.' }
    // Inside the rectangle (the checker's rule) and inside the box layers: hq clear kills the tagged entities of the box only.
    if (at[0] < 0 || at[0] >= c.sizeX || at[2] < 0 || at[2] >= c.sizeZ) return { ok: false, reason: 'Entity ' + i + ' at ' + at.join(' ') + ' lies outside the layout rectangle (x 0..' + (c.sizeX - 1) + ', z 0..' + (c.sizeZ - 1) + ').' }
    if (at[1] < -c.foundation || at[1] > c.clearTop) return { ok: false, reason: 'Entity ' + i + ' at ' + at.join(' ') + ' lies outside the box: ' + boxLayers }
    let nbt = consortiumHqStr(ents[i], 'nbt', '')
    if (/LootTable/i.test(nbt)) return { ok: false, reason: 'Entity ' + i + ': a LootTable is refused (rule 4.1).' }
    c.entities.push({ lx: at[0], ly: at[1], lz: at[2], dir: dir, summon: summon, nbt: nbt })
  }
  // Traps (layout format 2): { kind, cells [[x,y,z]], trigger [[x,y,z]] }, every cell inside the box.
  let trapsRaw = consortiumHqList(consortiumHqGet(raw, 'traps'))
  for (let i = 0; i < trapsRaw.length; i++) {
    let kind = consortiumHqStr(trapsRaw[i], 'kind', '')
    if (CONSORTIUM_HQ_TRAP_KINDS.indexOf(kind) < 0) return { ok: false, reason: 'Trap ' + i + ': unknown kind "' + kind + '" (pitfall, vent or arrows).' }
    let group = { kind: kind, cells: [], trigger: [] }
    for (let part of ['cells', 'trigger']) {
      let list = consortiumHqList(consortiumHqGet(trapsRaw[i], part))
      for (let j = 0; j < list.length; j++) {
        let xyz = consortiumHqInts(list[j])
        if (xyz.length !== 3) return { ok: false, reason: 'Trap ' + i + ' ' + part + ' ' + j + ' must be [x, y, z].' }
        if (xyz[0] < 0 || xyz[0] >= c.sizeX || xyz[2] < 0 || xyz[2] >= c.sizeZ || xyz[1] < -c.foundation || xyz[1] > c.clearTop) return { ok: false, reason: 'Trap ' + i + ' ' + part + ' ' + j + ' at ' + xyz.join(' ') + ' lies outside the layout box.' }
        group[part].push(xyz)
      }
    }
    if (group.cells.length === 0) return { ok: false, reason: 'Trap ' + i + ' has no cells.' }
    c.traps.push(group)
  }
  let marks = consortiumHqGet(raw, 'marks')
  let markNames = consortiumHqKeys(marks)
  for (let i = 0; i < markNames.length; i++) {
    let m = consortiumHqInts(consortiumHqGet(marks, markNames[i]))
    if (m.length !== 3) return { ok: false, reason: 'Mark ' + markNames[i] + ' must be [x, y, z].' }
    c.marks[markNames[i]] = m
  }
  for (let i = 0; i < ['spawn', 'arena', 'terminal'].length; i++) {
    if (c.marks[['spawn', 'arena', 'terminal'][i]] === undefined) return { ok: false, reason: 'Mark ' + ['spawn', 'arena', 'terminal'][i] + ' is mandatory.' }
  }
  // The world box: the rectangle plus the apron, layers -foundation..clear_top, rotated.
  let corners = [[-c.apron, -c.apron], [c.sizeX - 1 + c.apron, -c.apron], [-c.apron, c.sizeZ - 1 + c.apron], [c.sizeX - 1 + c.apron, c.sizeZ - 1 + c.apron]]
  let box = { x1: 1e9, z1: 1e9, x2: -1e9, z2: -1e9, y1: Y - c.foundation, y2: Y + c.clearTop }
  for (let i = 0; i < corners.length; i++) {
    let p = consortiumHqWorld(c, corners[i][0], 0, corners[i][1])
    box.x1 = Math.min(box.x1, p.getX()); box.x2 = Math.max(box.x2, p.getX())
    box.z1 = Math.min(box.z1, p.getZ()); box.z2 = Math.max(box.z2, p.getZ())
  }
  c.box = box
  // 254 on x: a run is packed as length | index << 8 and a run may span a whole row (width 255 would overflow)
  if (box.x2 - box.x1 >= 255 || box.z2 - box.z1 > 255 || box.y2 - box.y1 > 255) return { ok: false, reason: 'The box exceeds 254 blocks on x or 255 blocks on y or z.' }
  return { ok: true, c: c }
}

// ---- chunk forcing -----------------------------------------------------------------------------------

function consortiumHqForce(level, box, on) {
  let n = 0
  for (let cx = box.x1 >> 4; cx <= box.x2 >> 4; cx++) {
    for (let cz = box.z1 >> 4; cz <= box.z2 >> 4; cz++) {
      level.setChunkForced(cx, cz, on)
      n++
    }
  }
  return n
}

