// priority: 20
// The Consortium - the HQ spawn generator (docs/BADGES_AND_HQ.md part 2; PROJECT_RULES 4.1, 4.3, 4.6).
// Loads after consortium_events.js (20, path order) and needs consortium_lib.js (helpers) and, for the arena
// bookkeeping of `hq status` and `hq spawnpoint arena`, the events engine (consortiumArena, consortiumEvents,
// consortiumClaimManager: every call is typeof-guarded). Commands live in the HQ BLOCK of consortium_commands.js.
//
// What it does: /consortium hq build <x> <y> <z> <facing> [<layout>] places the layered layout of
// kubejs/data/consortium/consortium_hq/<layout>.json (generated by tools/hq/build-layout.mjs, checked by
// tools/hq/check-layout.mjs) around an anchor, rotated for one of the four facings, through an in-memory tick
// queue: pass 0 snapshots every position of the box (state plus block entity NBT, run-length encoded) into
// server.persistentData.consortium_hq.record and saves the world before the first write; pass 1 lays the
// foundation and the ground; pass 2 clears the box to air; pass 3 places the layers bottom to top with
// Level.setBlock flags 18 (clients only, known shape, the fastest mode measured) and the block entity NBT in
// the same tick; pass 4 finishes: the shape pass of the `connect` entries (Block.updateFromNeighbourShapes:
// setBlock never computes a placed block's own connections), the `last` entries (the Delivery Terminals after
// their panels: one formation scan), the waystone through the Waystones API, the tagged entities, the survival
// audit (state.canSurvive on every placed position), the force-load release, `built = true`, save-all and the
// report line. /consortium hq clear restores the snapshot (terminals and waystone first, then the bulk) and
// drops the record; hq status, spawnpoint and forget are the bookkeeping. No Consortium Core change: the
// Delivery Station forms from raw placement with no player (verified on the harness).
//
// State (server.persistentData.consortium_hq, its OWN root key: /consortium phase reset removes the
// `consortium` compound and must not touch the HQ bookkeeping): dim, layout, facing, anchor {x,y,z},
// box {x1,y1,z1,x2,y2,z2}, marks.<name> {x,y,z} (world), arena {ringMin, ringMax, pit}, forceloaded, written,
// built, by, special (ListTag of packed offsets: the last and api cells), record { palette (strings), runs
// (ints: packed offset, length | palette index << 8), bes [{p, t}] }. Offsets are measured from the box
// minimum corner: dx | dy << 8 | dz << 16 (the checker's 255 rule is this packing's limit).
//
// Reload safe: the queue is file-level state and dies with a /reload; the force-load ticket does not, so the
// first tick after every script load releases a ticket left by an interrupted build or clear and warns
// (ServerEvents.loaded is not posted by /reload in KubeJS 2101.7.2). No scheduleRepeating.
//
// Rhino note: `const` only at file top level or as the first statements of a function; `let` in blocks.

